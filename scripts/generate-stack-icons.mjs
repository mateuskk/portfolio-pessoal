/**
 * Bakes the brand marks the stack panel actually uses into `lib/stack-icons.ts`.
 *
 * Importing `simple-icons` at runtime would pull a barrel of ~3300 icons and
 * leave tree-shaking to decide how much of it survives. The panel needs about
 * twenty, so they are generated once and committed — the bundle then carries
 * exactly the path data that gets drawn, and `simple-icons` stays a dev-only
 * dependency.
 *
 * The slug list is not maintained here. It is read out of the files that
 * actually name slugs, so adding a tool with an icon is a one-line edit
 * followed by:
 *
 *   node scripts/generate-stack-icons.mjs
 */
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const catalogDir = resolve(root, 'lib');
const outPath = resolve(root, 'lib/stack-icons.ts');
// Read off disk rather than imported: simple-icons does not export its own
// `package.json` subpath.
const version = JSON.parse(
  readFileSync(resolve(root, 'node_modules/simple-icons/package.json'), 'utf8'),
).version;
const icons = Object.values(require('simple-icons')).filter(Boolean);

/**
 * Every catalog, found rather than listed.
 *
 * Naming the sources by hand is what broke this before: the stack content and
 * the projects' own technology map both named slugs, only one was read, and
 * trimming a tool from the content silently dropped an icon the other still
 * asked for. A generator that reads one of two sources is worse than none,
 * because it looks authoritative.
 *
 * So the rule is structural instead of remembered — a catalog is a
 * `lib/*-catalog.ts`, and they are all read. Adding one cannot leave it out.
 */
const catalogs = readdirSync(catalogDir)
  .filter((entry) => entry.endsWith('-catalog.ts'))
  .sort()
  .map((entry) => resolve(catalogDir, entry));

if (catalogs.length === 0) {
  throw new Error(`No catalogs found in ${catalogDir}. Expected a \`*-catalog.ts\`.`);
}

const found = new Set();
for (const catalog of catalogs) {
  for (const match of readFileSync(catalog, 'utf8').matchAll(
    /\bicon:\s*["']([a-z0-9]+)["']/g,
  )) {
    // Recharts does not publish a Simple Icons mark. Its project chip uses a
    // small chart glyph from Lucide, so it must not enter this generated map.
    if (match[1] !== 'recharts') found.add(match[1]);
  }
}
const slugs = [...found].sort((a, b) => a.localeCompare(b));

if (slugs.length === 0) {
  throw new Error(
    `No icon slugs found in ${catalogDir}. Expected entries like \`icon: "react"\`.`,
  );
}

const entries = slugs.map((slug) => {
  const icon = icons.find((candidate) => candidate.slug === slug);
  if (!icon) {
    throw new Error(
      `simple-icons@${version} has no icon with slug "${slug}". ` +
        `Either fix the slug in the catalog that names it or set \`icon: null\` and let it use the fallback mark.`,
    );
  }
  return { slug, title: icon.title, hex: `#${icon.hex}`, path: icon.path };
});

const body = entries
  .map(
    ({ slug, title, hex, path }) =>
      `  ${slug}: {\n    title: ${JSON.stringify(title)},\n    hex: ${JSON.stringify(hex)},\n    path: ${JSON.stringify(path)},\n  },`,
  )
  .join('\n');

writeFileSync(
  outPath,
  `// Generated by scripts/generate-stack-icons.mjs from simple-icons@${version}.
// Do not edit by hand — add the entry to a \`lib/*-catalog.ts\` and re-run the script.
//
// \`hex\` is the brand's own colour. It is not necessarily legible on this
// site's near-black ground, so nothing renders it directly: see
// \`getStackIconColor\` in components/stack/stack-icon.tsx.

export type StackIconData = {
  title: string;
  hex: string;
  path: string;
};

export const stackIcons = {
${body}
} satisfies Record<string, StackIconData>;

export type StackIconSlug = keyof typeof stackIcons;
`,
  'utf8',
);

console.log(`Wrote ${entries.length} icons to lib/stack-icons.ts:`);
console.log(
  entries.map((entry) => `  ${entry.slug.padEnd(20)} ${entry.hex}`).join('\n'),
);
